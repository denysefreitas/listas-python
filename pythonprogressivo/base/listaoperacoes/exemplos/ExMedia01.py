# Crie um script que pede a nota de Português e a de Inglês, e forneça a média das duas notas.

nota_portugues = float(input("Informe a nota de Português: "))
nota_ingles = float(input("Informe a nota de Inglês: "))

media = (nota_portugues + nota_ingles)/2

print(f"A média das notas é {media}")
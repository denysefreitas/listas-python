semana = ['Segunda', 'Terça', 'Quarta', 'Quinta', 'Sexta', 'Sábado', 'Domingo']

print("Uso do 'in':")
print(f"Fevereiro está na lista 'semana'?: {'Fevereiro' in semana}")
print(f"Terça está na lista 'semana'?: {'Terça' in semana}")

print("\nUso do 'not in':")
print(f"Fevereiro não está na lista 'semana'?: {'Fevereiro' not in semana}")
print(f"Terça não está na lista 'semana'?: {'Terça' not in semana}")
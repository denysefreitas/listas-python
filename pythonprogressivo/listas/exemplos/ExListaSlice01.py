semana = ['Segunda', 'Terça', 'Quarta', 'Quinta', 'Sexta', 'Sábado', 'Domingo' ]

print(semana[0:5]) # exibe os itens de índice 0, 1, 2, 3, 4, 5
print(semana[:5]) # exibe os itens do início da lista (0) até 5
print(semana[5:]) # exibe os itens de índice 5 até o fim da lista (6)
print(semana[:]) # exibe todos os itens da lista